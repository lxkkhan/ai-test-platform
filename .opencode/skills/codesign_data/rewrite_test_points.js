async function getToken() {
  const apiUser = "tapd-app-53825c";
  const apiPass = "A3BEF211-FC08-81BB-D43B-3CEC09FF0AF9";
  const basic = Buffer.from(`${apiUser}:${apiPass}`).toString('base64');
  const r = await fetch(`${API_URL}/tokens/request_token`, {
    method: 'POST', headers: { Authorization: `Basic ${basic}` },
    body: new URLSearchParams({ grant_type: 'client_credentials' })
  });
  return (await r.json()).data.access_token;
}

function buildTestPointsHtml(tps) {
  if (!tps || tps.length === 0) return '';

  // Group by type for better readability
  const groups = {};
  tps.forEach(tp => {
    const cat = tp.type.split('-')[0];
    if (!groups[cat]) groups[cat] = [];
    groups[cat].push(tp);
  });

  let html = `\n<h5>测试要点（高级测试工程师）</h5>
<table border="1" cellpadding="4" cellspacing="0" style="border-collapse:collapse;width:100%;font-size:12px;margin-bottom:8px">
  <tr style="background:#f0f0f0"><th>序号</th><th>测试场景</th><th>测试类型</th><th>验证点</th></tr>`;

  let idx = 1;
  const typeOrder = ['字段校验', '唯一性约束', '状态流转', '业务规则', '流程集成', '查询逻辑', '业务流程', '异常恢复', '权限控制'];
  for (const cat of typeOrder) {
    if (!groups[cat]) continue;
    groups[cat].forEach(tp => {
      html += `  <tr><td>${idx++}</td><td>${tp.name}</td><td>${tp.type}</td><td>${tp.check}</td></tr>`;
    });
  }

  html += `</table>`;
  return html;
}

async function updateStory(sid, html) {
  const token = await getToken();
  const fullId = `116272130300${sid}`;

  const r = await fetch(`${API_URL}/stories?workspace_id=${ws}&id=${fullId}&fields=description`, {
    headers: { Authorization: `Bearer ${token}` }
  });
  const d = await r.json();
  let desc = d.data?.[0]?.Story?.description || '';

  // Remove old test points section
  desc = desc.replace(/<h5>测试要点.*?<\/h5>\s*<table[\s\S]*?<\/table>/g, '');

  // Append new test points before closing meta
  const timeIdx = desc.lastIndexOf('分析时间');
  if (timeIdx >= 0) {
    const before = desc.substring(0, timeIdx);
    const after = desc.substring(timeIdx);
    desc = before + html + '\n' + after;
  } else {
    desc += html;
  }

  const body = new URLSearchParams({ workspace_id: ws, description: desc });
  const ur = await fetch(`${API_URL}/stories/${fullId}`, {
    method: 'POST', headers: { Authorization: `Bearer ${token}` }, body
  });
  const ud = await ur.json();
  return ud.status === 1;
}

